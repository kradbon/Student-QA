CREATE DATABASE IF NOT EXISTS student_qa CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE student_qa;

SET FOREIGN_KEY_CHECKS=0;
DROP TABLE IF EXISTS notifications, reports, votes, question_tags, tags, answers, questions, users, roles;
SET FOREIGN_KEY_CHECKS=1;

CREATE TABLE roles (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 name VARCHAR(30) NOT NULL UNIQUE
) ENGINE=InnoDB;

CREATE TABLE users (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 role_id BIGINT UNSIGNED NOT NULL,
 full_name VARCHAR(120) NOT NULL,
 email VARCHAR(190) NOT NULL UNIQUE,
 password_hash VARCHAR(255) NOT NULL,
 avatar_path VARCHAR(255) NULL,
 reputation INT NOT NULL DEFAULT 0,
 status ENUM('active','blocked') NOT NULL DEFAULT 'active',
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 CONSTRAINT fk_users_role FOREIGN KEY(role_id) REFERENCES roles(id) ON DELETE RESTRICT,
 INDEX idx_users_reputation(reputation)
) ENGINE=InnoDB;

CREATE TABLE questions (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 user_id BIGINT UNSIGNED NOT NULL,
 title VARCHAR(180) NOT NULL,
 body TEXT NOT NULL,
 status ENUM('published','hidden','closed') NOT NULL DEFAULT 'published',
 views INT UNSIGNED NOT NULL DEFAULT 0,
 accepted_answer_id BIGINT UNSIGNED NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 CONSTRAINT fk_questions_user FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE,
 INDEX idx_questions_created(created_at),
 FULLTEXT INDEX ft_questions(title, body)
) ENGINE=InnoDB;

CREATE TABLE answers (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 question_id BIGINT UNSIGNED NOT NULL,
 user_id BIGINT UNSIGNED NOT NULL,
 body TEXT NOT NULL,
 is_accepted TINYINT(1) NOT NULL DEFAULT 0,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 CONSTRAINT fk_answers_question FOREIGN KEY(question_id) REFERENCES questions(id) ON DELETE CASCADE,
 CONSTRAINT fk_answers_user FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE,
 INDEX idx_answers_question(question_id)
) ENGINE=InnoDB;

ALTER TABLE questions ADD CONSTRAINT fk_questions_accepted_answer
 FOREIGN KEY(accepted_answer_id) REFERENCES answers(id) ON DELETE SET NULL;

CREATE TABLE tags (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 name VARCHAR(40) NOT NULL UNIQUE,
 description VARCHAR(255) NULL
) ENGINE=InnoDB;

CREATE TABLE question_tags (
 question_id BIGINT UNSIGNED NOT NULL,
 tag_id BIGINT UNSIGNED NOT NULL,
 PRIMARY KEY(question_id, tag_id),
 CONSTRAINT fk_qt_question FOREIGN KEY(question_id) REFERENCES questions(id) ON DELETE CASCADE,
 CONSTRAINT fk_qt_tag FOREIGN KEY(tag_id) REFERENCES tags(id) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE votes (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 user_id BIGINT UNSIGNED NOT NULL,
 answer_id BIGINT UNSIGNED NOT NULL,
 value TINYINT NOT NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT chk_vote_value CHECK(value IN (-1,1)),
 CONSTRAINT uq_vote_user_answer UNIQUE(user_id, answer_id),
 CONSTRAINT fk_votes_user FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE,
 CONSTRAINT fk_votes_answer FOREIGN KEY(answer_id) REFERENCES answers(id) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE reports (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 reporter_id BIGINT UNSIGNED NOT NULL,
 target_type ENUM('question','answer') NOT NULL,
 target_id BIGINT UNSIGNED NOT NULL,
 reason VARCHAR(500) NOT NULL,
 status ENUM('pending','reviewed','dismissed') NOT NULL DEFAULT 'pending',
 reviewed_by BIGINT UNSIGNED NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT fk_reports_reporter FOREIGN KEY(reporter_id) REFERENCES users(id) ON DELETE CASCADE,
 CONSTRAINT fk_reports_reviewer FOREIGN KEY(reviewed_by) REFERENCES users(id) ON DELETE SET NULL,
 INDEX idx_reports_status(status)
) ENGINE=InnoDB;

CREATE TABLE notifications (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 user_id BIGINT UNSIGNED NOT NULL,
 message VARCHAR(255) NOT NULL,
 link VARCHAR(255) NULL,
 is_read TINYINT(1) NOT NULL DEFAULT 0,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT fk_notifications_user FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE,
 INDEX idx_notifications_user_read(user_id,is_read)
) ENGINE=InnoDB;
